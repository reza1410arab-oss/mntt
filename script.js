// ========================================
// ACAK DATA
// ========================================

function ambilAcak(data) {

    if (!Array.isArray(data) || data.length === 0) {
        return "";
    }

    return data[
        Math.floor(Math.random() * data.length)
    ];

}


// ========================================
// COPY TEXT
// ========================================

async function copyTeks(text, button) {

    if (!text) return;

    let berhasil = false;

    try {

        if (
            navigator.clipboard &&
            window.isSecureContext
        ) {

            await navigator.clipboard.writeText(text);

            berhasil = true;
        }

    } catch (error) {

        console.log("Clipboard API gagal:", error);

    }


    // Fallback
    if (!berhasil) {

        const textarea =
            document.createElement("textarea");

        textarea.value = text;

        textarea.style.position = "fixed";
        textarea.style.left = "-9999px";
        textarea.style.top = "0";

        document.body.appendChild(textarea);

        textarea.focus();
        textarea.select();

        try {

            berhasil =
                document.execCommand("copy");

        } catch (error) {

            console.log("Copy gagal:", error);

        }

        textarea.remove();

    }


    if (button && berhasil) {

        const teksAwal =
            button.innerHTML;

        button.innerHTML =
            "COPIED ✔";

        button.disabled = true;

        setTimeout(() => {

            button.innerHTML =
                teksAwal;

            button.disabled = false;

        }, 1500);

    }

}


// ========================================
// COPY FOTO GAME
// ========================================

async function copyFotoGame(img, button) {

    if (!img) {
        console.error("❌ Foto tidak ditemukan!");
        return;
    }

    try {

        // Tunggu gambar selesai dimuat
        if (
            !img.complete ||
            img.naturalWidth === 0
        ) {

            await new Promise((resolve, reject) => {

                img.addEventListener(
                    "load",
                    resolve,
                    { once: true }
                );

                img.addEventListener(
                    "error",
                    reject,
                    { once: true }
                );

            });

        }


        // Buat canvas
        const canvas =
            document.createElement("canvas");

        canvas.width =
            img.naturalWidth;

        canvas.height =
            img.naturalHeight;


        const ctx =
            canvas.getContext("2d");

        ctx.drawImage(
            img,
            0,
            0
        );


        // Buat PNG
        const blob =
            await new Promise((resolve) => {

                canvas.toBlob(
                    resolve,
                    "image/png"
                );

            });


        if (!blob) {
            throw new Error(
                "Gagal membuat gambar."
            );
        }


        // Pastikan browser support
        if (
            !navigator.clipboard ||
            typeof ClipboardItem === "undefined"
        ) {

            throw new Error(
                "Browser tidak mendukung copy foto."
            );

        }


        // COPY FOTO
        await navigator.clipboard.write([
            new ClipboardItem({
                "image/png": blob
            })
        ]);


        // Berhasil
        const teksAwal =
            button.innerHTML;

        button.innerHTML =
            "COPIED FOTO ✔";

        button.disabled = true;


        setTimeout(() => {

            button.innerHTML =
                teksAwal;

            button.disabled = false;

        }, 1500);


        console.log(
            "✅ FOTO BERHASIL DICOPY:",
            img.src
        );


    } catch (error) {

        console.error(
            "❌ COPY FOTO GAGAL:",
            error
        );


        const teksAwal =
            button.innerHTML;

        button.innerHTML =
            "GAGAL COPY ❌";

        button.disabled = true;


        setTimeout(() => {

            button.innerHTML =
                teksAwal;

            button.disabled = false;

        }, 2000);

    }

}


// ========================================
// SARAN GAME
// ========================================

function saranGame(id, button) {

    const game =
        dataGame[id];

    if (!game) {

        console.error(
            "Game tidak ditemukan:",
            id
        );

        return;
    }


    const teks =
        ambilAcak(game.saran);


    copyTeks(
        teks,
        button
    );

}


// ========================================
// POLA GAME
// KLIK = COPY FOTO
// ========================================

function polaGame(id, button) {

    const game =
        dataGame[id];

    if (!game) {

        console.error(
            "Game tidak ditemukan:",
            id
        );

        return;
    }


    const gameBox =
        button.closest(".game-box");


    if (!gameBox) {

        console.error(
            "Game box tidak ditemukan!"
        );

        return;
    }


    const img =
        gameBox.querySelector(
            ".game-image"
        );


    if (!img) {

        console.error(
            "Foto game tidak ditemukan!"
        );

        return;
    }


    // JANGAN COPY TEKS POLA
    // LANGSUNG COPY FOTO

    copyFotoGame(
        img,
        button
    );

}


