// ========================================
// ACAK DATA
// ========================================

function ambilAcak(data) {

    if (!Array.isArray(data) || data.length === 0) {
        return "";
    }

    return data[
        Math.floor(Math.random() * data.length)
    ];
}


// ========================================
// COPY TEKS
// ========================================

async function copyTeks(text, button) {

    if (!text) {
        return;
    }

    let berhasil = false;

    try {

        if (
            navigator.clipboard &&
            window.isSecureContext
        ) {

            await navigator.clipboard.writeText(text);

            berhasil = true;

        }

    } catch (error) {

        console.error(
            "Clipboard API gagal:",
            error
        );

    }


    // FALLBACK COPY TEKS
    if (!berhasil) {

        const textarea =
            document.createElement("textarea");

        textarea.value = text;

        textarea.style.position = "fixed";
        textarea.style.left = "-9999px";
        textarea.style.top = "0";
        textarea.style.opacity = "0";

        document.body.appendChild(textarea);

        textarea.focus();
        textarea.select();

        try {

            berhasil =
                document.execCommand("copy");

        } catch (error) {

            console.error(
                "Fallback copy gagal:",
                error
            );

        }

        textarea.remove();

    }


    if (berhasil && button) {

        tombolBerhasil(
            button,
            "COPIED ✔",
            1500
        );

    } else {

        tombolGagal(
            button,
            "GAGAL COPY ❌",
            2000
        );

    }

}


// ========================================
// TOMBOL BERHASIL
// ========================================

function tombolBerhasil(button, text, waktu) {

    if (!button) {
        return;
    }

    const teksAwal =
        button.innerHTML;

    button.innerHTML = text;
    button.disabled = true;

    setTimeout(() => {

        button.innerHTML =
            teksAwal;

        button.disabled = false;

    }, waktu);

}


// ========================================
// TOMBOL GAGAL
// ========================================

function tombolGagal(button, text, waktu) {

    if (!button) {
        return;
    }

    const teksAwal =
        button.innerHTML;

    button.innerHTML = text;
    button.disabled = true;

    setTimeout(() => {

        button.innerHTML =
            teksAwal;

        button.disabled = false;

    }, waktu);

}


// ========================================
// COPY FOTO
// ========================================

async function copyFotoGame(img, button) {

    if (!img) {

        console.error(
            "❌ Elemen foto tidak ditemukan!"
        );

        tombolGagal(
            button,
            "FOTO TIDAK ADA ❌",
            2000
        );

        return;
    }


    try {

        // ========================================
        // TUNGGU FOTO SELESAI DIMUAT
        // ========================================

        if (
            !img.complete ||
            img.naturalWidth === 0
        ) {

            await new Promise(
                (resolve, reject) => {

                    const selesai =
                        () => {
                            cleanup();
                            resolve();
                        };

                    const gagal =
                        () => {
                            cleanup();
                            reject(
                                new Error(
                                    "Foto gagal dimuat."
                                )
                            );
                        };

                    const cleanup =
                        () => {

                            img.removeEventListener(
                                "load",
                                selesai
                            );

                            img.removeEventListener(
                                "error",
                                gagal
                            );

                        };


                    img.addEventListener(
                        "load",
                        selesai,
                        { once: true }
                    );

                    img.addEventListener(
                        "error",
                        gagal,
                        { once: true }
                    );

                }
            );

        }


        // ========================================
        // CEK FOTO
        // ========================================

        if (
            img.naturalWidth === 0 ||
            img.naturalHeight === 0
        ) {

            throw new Error(
                "Ukuran foto tidak valid."
            );

        }


        // ========================================
        // BUAT CANVAS
        // ========================================

        const canvas =
            document.createElement("canvas");

        canvas.width =
            img.naturalWidth;

        canvas.height =
            img.naturalHeight;


        const ctx =
            canvas.getContext("2d");


        if (!ctx) {

            throw new Error(
                "Canvas tidak tersedia."
            );

        }


        // ========================================
        // GAMBAR KE CANVAS
        // ========================================

        ctx.drawImage(
            img,
            0,
            0,
            img.naturalWidth,
            img.naturalHeight
        );


        // ========================================
        // UBAH CANVAS MENJADI PNG
        // ========================================

        const blob =
            await new Promise(
                (resolve) => {

                    canvas.toBlob(
                        resolve,
                        "image/png"
                    );

                }
            );


        if (!blob) {

            throw new Error(
                "Gagal membuat PNG."
            );

        }


        // ========================================
        // CEK SUPPORT CLIPBOARD GAMBAR
        // ========================================

        if (
            !navigator.clipboard ||
            typeof ClipboardItem === "undefined"
        ) {

            throw new Error(
                "Browser tidak mendukung copy gambar."
            );

        }


        // ========================================
        // COPY FOTO KE CLIPBOARD
        // ========================================

        await navigator.clipboard.write([
            new ClipboardItem({
                "image/png": blob
            })
        ]);


        // ========================================
        // BERHASIL
        // ========================================

        console.log(
            "✅ FOTO BERHASIL DICOPY:",
            img.src
        );


        tombolBerhasil(
            button,
            "FOTO COPIED ✔",
            1500
        );


    } catch (error) {

        console.error(
            "❌ COPY FOTO GAGAL:",
            error
        );


        tombolGagal(
            button,
            "GAGAL COPY FOTO ❌",
            2500
        );

    }

}


// ========================================
// SARAN GAME
// ========================================

function saranGame(id, button) {

    const game =
        dataGame[id];


    if (!game) {

        console.error(
            "❌ Game tidak ditemukan:",
            id
        );

        return;
    }


    const teks =
        ambilAcak(
            game.saran
        );


    copyTeks(
        teks,
        button
    );

}


// ========================================
// POLA GAME
// KLIK POLA = COPY FOTO
// ========================================

function polaGame(id, button) {

    const game =
        dataGame[id];


    if (!game) {

        console.error(
            "❌ Game tidak ditemukan:",
            id
        );

        return;
    }


    // Ambil CARD tempat tombol berada
    const gameBox =
        button.closest(
            ".game-box"
        );


    if (!gameBox) {

        console.error(
            "❌ .game-box tidak ditemukan!"
        );

        return;
    }


    // Ambil foto dari card yang sama
    const img =
        gameBox.querySelector(
            ".game-image"
        );


    if (!img) {

        console.error(
            "❌ .game-image tidak ditemukan!"
        );

        return;
    }


    // ========================================
    // PENTING:
    // TIDAK COPY game.pola
    // LANGSUNG COPY FOTO
    // ========================================

    copyFotoGame(
        img,
        button
    );

}


