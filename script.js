// ========================================
// ACAK DATA
// ========================================

function ambilAcak(data) {

    if (!Array.isArray(data) || data.length === 0) {
        return "";
    }

    return data[
        Math.floor(Math.random() * data.length)
    ];
}


// ========================================
// COPY TEXT
// ========================================

async function copyTeks(text, button) {

    if (!text) {
        return;
    }

    try {

        await navigator.clipboard.writeText(text);

        const teksAwal = button.innerHTML;

        button.innerHTML = "COPIED ✔";
        button.disabled = true;

        setTimeout(() => {

            button.innerHTML = teksAwal;
            button.disabled = false;

        }, 1500);

    } catch (error) {

        console.error(
            "❌ Copy teks gagal:",
            error
        );

    }

}


// ========================================
// COPY FOTO GAME
// ========================================

async function copyFotoGame(img, button) {

    try {

        if (!img) {
            throw new Error("Foto tidak ditemukan");
        }

        // Pastikan gambar sudah selesai dimuat
        if (!img.complete || img.naturalWidth === 0) {

            await new Promise((resolve, reject) => {

                img.onload = resolve;
                img.onerror = reject;

            });

        }


        // ========================================
        // BUAT CANVAS
        // ========================================

        const canvas =
            document.createElement("canvas");

        canvas.width =
            img.naturalWidth;

        canvas.height =
            img.naturalHeight;


        const ctx =
            canvas.getContext("2d");


        ctx.drawImage(
            img,
            0,
            0,
            canvas.width,
            canvas.height
        );


        // ========================================
        // BUAT FILE PNG
        // ========================================

        const blob =
            await new Promise((resolve, reject) => {

                canvas.toBlob(
                    result => {

                        if (result) {
                            resolve(result);
                        } else {
                            reject(
                                new Error(
                                    "Gagal membuat PNG"
                                )
                            );
                        }

                    },
                    "image/png"
                );

            });


        // ========================================
        // COPY KE CLIPBOARD
        // ========================================

        if (
            !navigator.clipboard ||
            typeof ClipboardItem === "undefined"
        ) {

            throw new Error(
                "Browser tidak mendukung copy gambar"
            );

        }


        await navigator.clipboard.write([
            new ClipboardItem({
                "image/png": blob
            })
        ]);


        // ========================================
        // BERHASIL
        // ========================================

        const teksAwal =
            button.innerHTML;

        button.innerHTML =
            "COPIED FOTO ✔";

        button.disabled = true;


        setTimeout(() => {

            button.innerHTML =
                teksAwal;

            button.disabled = false;

        }, 1500);


        console.log(
            "✅ FOTO BERHASIL DICOPY:",
            img.src
        );


    } catch (error) {

        console.error(
            "❌ COPY FOTO GAGAL:",
            error
        );

        const teksAwal =
            button.innerHTML;

        button.innerHTML =
            "GAGAL COPY ❌";


        setTimeout(() => {

            button.innerHTML =
                teksAwal;

        }, 2000);

    }

}


// ========================================
// SARAN GAME
// ========================================

function saranGame(id, button) {

    const game =
        dataGame[id];

    if (!game) {
        console.error(
            "Game tidak ditemukan:",
            id
        );
        return;
    }


    // SARAN = COPY TEKS
    const teks =
        ambilAcak(game.saran);


    copyTeks(
        teks,
        button
    );

}


// ========================================
// POLA GAME
// ========================================
// PENTING:
// POLA GAME TIDAK COPY TEKS POLA.
// POLA GAME LANGSUNG COPY FOTO.
// ========================================

function polaGame(id, button) {

    const gameBox =
        button.closest(".game-box");


    if (!gameBox) {

        console.error(
            "❌ Game box tidak ditemukan!"
        );

        return;
    }


    const img =
        gameBox.querySelector(
            ".game-image"
        );


    if (!img) {

        console.error(
            "❌ Foto game tidak ditemukan!"
        );

        return;
    }


    // LANGSUNG COPY FOTO
    copyFotoGame(
        img,
        button
    );

}


